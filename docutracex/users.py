"""Users, sessions and the MCP token (``config/users.json``, ``config/sessions.json``,
``config/mcp_token.txt`` — all git-ignored, kept across updates).

- **Users**: ``admin`` (manages users) and ordinary users; everyone sees the same
  cases and can use every feature. Passwords are stored as scrypt hashes
  (standard library, salted, no plain text anywhere).
- **First start**: until the admin password is set, the app only shows the
  "set the admin password" screen.
- **Sessions**: a random token in an HttpOnly cookie; it expires after
  SESSION_IDLE_HOURS without activity and survives restarts.
- **Login throttling**: MAX_FAILURES wrong passwords from one address lock it
  out for LOCKOUT_MINUTES.
- **MCP token**: the bearer token the MCP server over HTTP requires; generated
  on first use, regenerated by the admin (AI → MCP), read by the MCP process on
  every request so a new one takes effect at once.

Recovery from the console of the machine (no web access needed)::

    python -m docutracex.users reset-admin            # asks for the new password
    python -m docutracex.users list
    python -m docutracex.users mcp-token [--regenerate]
"""

from __future__ import annotations

import base64
import hashlib
import hmac
import json
import os
import re
import secrets
import threading
import time
from pathlib import Path
from typing import Any

from .appsettings import config_dir

ADMIN = "admin"
ROLES = ("admin", "user")
MIN_PASSWORD = 8
SESSION_IDLE_HOURS = 12
MAX_FAILURES = 5
LOCKOUT_MINUTES = 5
COOKIE = "dtx_session"
_NAME = re.compile(r"^[A-Za-z0-9._@-]{2,64}$")
_SCRYPT = {"n": 2 ** 14, "r": 8, "p": 1, "dklen": 32}

_lock = threading.RLock()
_failures: dict[str, list[float]] = {}
_touch_every = 300.0          # write a session's "last seen" at most every 5 minutes


class AuthError(ValueError):
    """A request the user can fix (bad name, short password, unknown user…)."""


# --- storage ------------------------------------------------------------------
def _users_path() -> Path:
    return config_dir() / "users.json"


def _sessions_path() -> Path:
    return config_dir() / "sessions.json"


def _token_path() -> Path:
    return config_dir() / "mcp_token.txt"


def _read(p: Path) -> dict:
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}


def _write(p: Path, data: dict) -> None:
    p.parent.mkdir(parents=True, exist_ok=True)
    tmp = p.with_suffix(p.suffix + ".tmp")
    tmp.write_text(json.dumps(data, indent=2, ensure_ascii=False), encoding="utf-8")
    try:
        os.chmod(tmp, 0o600)
    except OSError:
        pass
    os.replace(tmp, p)


def _users() -> dict[str, dict]:
    return _read(_users_path()).get("users") or {}


def _save_users(users: dict[str, dict]) -> None:
    _write(_users_path(), {"users": users})


# --- passwords ----------------------------------------------------------------
def hash_password(password: str) -> str:
    salt = os.urandom(16)
    dk = hashlib.scrypt(password.encode("utf-8"), salt=salt, **_SCRYPT)
    return "scrypt${n}${r}${p}${s}${h}".format(
        n=_SCRYPT["n"], r=_SCRYPT["r"], p=_SCRYPT["p"],
        s=base64.b64encode(salt).decode(), h=base64.b64encode(dk).decode())


def check_password(password: str, stored: str) -> bool:
    try:
        algo, n, r, p, s, h = stored.split("$")
        if algo != "scrypt":
            return False
        dk = hashlib.scrypt(password.encode("utf-8"), salt=base64.b64decode(s),
                            n=int(n), r=int(r), p=int(p), dklen=len(base64.b64decode(h)))
        return hmac.compare_digest(dk, base64.b64decode(h))
    except (ValueError, TypeError):
        return False


def _check_new_password(password: str) -> None:
    if not isinstance(password, str) or len(password) < MIN_PASSWORD:
        raise AuthError(f"The password needs at least {MIN_PASSWORD} characters.")


# --- users --------------------------------------------------------------------
def needs_setup() -> bool:
    """True until the admin password has been set (first start)."""
    return ADMIN not in _users()


def setup_admin(password: str) -> dict:
    with _lock:
        if not needs_setup():
            raise AuthError("The admin password is already set.")
        _check_new_password(password)
        users = _users()
        users[ADMIN] = {"hash": hash_password(password), "role": "admin", "active": True,
                        "created": _now()}
        _save_users(users)
        return public(ADMIN)


def public(name: str) -> dict:
    u = _users().get(name) or {}
    return {"username": name, "role": u.get("role", "user"), "active": bool(u.get("active", True)),
            "created": u.get("created", ""), "last_login": u.get("last_login", "")}


def list_users() -> list[dict]:
    return [public(n) for n in sorted(_users(), key=lambda n: (n != ADMIN, n.lower()))]


def role(name: str) -> str:
    return (_users().get(name) or {}).get("role", "user")


def create_user(name: str, password: str, user_role: str = "user") -> dict:
    with _lock:
        name = (name or "").strip()
        if not _NAME.match(name):
            raise AuthError("User names are 2–64 letters, digits, dots, dashes, underscores or @.")
        users = _users()
        if name.lower() in {n.lower() for n in users}:
            raise AuthError(f"User {name} already exists.")
        if user_role not in ROLES:
            raise AuthError("Role must be admin or user.")
        _check_new_password(password)
        users[name] = {"hash": hash_password(password), "role": user_role, "active": True, "created": _now()}
        _save_users(users)
        return public(name)


def update_user(name: str, *, password: str | None = None, active: bool | None = None,
                user_role: str | None = None) -> dict:
    with _lock:
        users = _users()
        if name not in users:
            raise AuthError(f"Unknown user {name}.")
        u = users[name]
        if password is not None:
            _check_new_password(password)
            u["hash"] = hash_password(password)
            drop_user_sessions(name)
        if active is not None:
            if name == ADMIN and not active:
                raise AuthError("The admin account cannot be disabled.")
            u["active"] = bool(active)
            if not active:
                drop_user_sessions(name)
        if user_role is not None:
            if user_role not in ROLES:
                raise AuthError("Role must be admin or user.")
            if name == ADMIN and user_role != "admin":
                raise AuthError("The admin account keeps the admin role.")
            u["role"] = user_role
        _save_users(users)
        return public(name)


def delete_user(name: str) -> None:
    with _lock:
        if name == ADMIN:
            raise AuthError("The admin account cannot be deleted.")
        users = _users()
        if users.pop(name, None) is None:
            raise AuthError(f"Unknown user {name}.")
        _save_users(users)
        drop_user_sessions(name)


def change_own_password(name: str, current: str, new: str) -> None:
    u = _users().get(name)
    if not u or not check_password(current or "", u.get("hash", "")):
        raise AuthError("The current password is not right.")
    update_user(name, password=new)


# --- login and throttling -----------------------------------------------------
def locked_out(addr: str) -> int:
    """Seconds left of a lockout for this address (0 = may try)."""
    now = time.time()
    with _lock:
        recent = [t for t in _failures.get(addr, []) if now - t < LOCKOUT_MINUTES * 60]
        _failures[addr] = recent
        if len(recent) >= MAX_FAILURES:
            return int(LOCKOUT_MINUTES * 60 - (now - recent[0])) + 1
    return 0


def authenticate(name: str, password: str, addr: str = "") -> str | None:
    """The user name when the password is right and the account is active."""
    if locked_out(addr):
        return None
    u = _users().get(name or "")
    if u and u.get("active", True) and check_password(password or "", u.get("hash", "")):
        with _lock:
            _failures.pop(addr, None)
            users = _users()
            users[name]["last_login"] = _now()
            _save_users(users)
        return name
    with _lock:
        _failures.setdefault(addr, []).append(time.time())
    return None


# --- sessions -----------------------------------------------------------------
def create_session(name: str) -> str:
    token = secrets.token_urlsafe(32)
    with _lock:
        s = _read(_sessions_path())
        _expire(s)
        s[_key(token)] = {"user": name, "created": time.time(), "last": time.time()}
        _write(_sessions_path(), s)
    return token


def session_user(token: str | None) -> str | None:
    """The signed-in user of a session cookie, or None (unknown, expired, disabled)."""
    if not token:
        return None
    with _lock:
        s = _read(_sessions_path())
        rec = s.get(_key(token))
        if not rec:
            return None
        now = time.time()
        if now - rec.get("last", 0) > SESSION_IDLE_HOURS * 3600:
            s.pop(_key(token), None)
            _write(_sessions_path(), s)
            return None
        u = _users().get(rec.get("user", ""))
        if not u or not u.get("active", True):
            return None
        if now - rec.get("last", 0) > _touch_every:
            rec["last"] = now
            _write(_sessions_path(), s)
        return rec["user"]


def drop_session(token: str | None) -> None:
    if not token:
        return
    with _lock:
        s = _read(_sessions_path())
        if s.pop(_key(token), None) is not None:
            _write(_sessions_path(), s)


def drop_user_sessions(name: str) -> None:
    with _lock:
        s = _read(_sessions_path())
        kept = {k: v for k, v in s.items() if v.get("user") != name}
        if len(kept) != len(s):
            _write(_sessions_path(), kept)


def _expire(s: dict) -> None:
    now = time.time()
    for k in [k for k, v in s.items() if now - v.get("last", 0) > SESSION_IDLE_HOURS * 3600]:
        s.pop(k, None)


def _key(token: str) -> str:
    """Sessions are stored by the hash of their token: the file alone signs nobody in."""
    return hashlib.sha256(token.encode()).hexdigest()


# --- MCP token ----------------------------------------------------------------
def mcp_token() -> str:
    """The MCP-over-HTTP bearer token, created on first use."""
    with _lock:
        p = _token_path()
        try:
            t = p.read_text(encoding="utf-8").strip()
            if len(t) >= 32:
                return t
        except OSError:
            pass
        return regenerate_mcp_token()


def regenerate_mcp_token() -> str:
    with _lock:
        t = "dtx_" + secrets.token_urlsafe(32)
        p = _token_path()
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(t, encoding="utf-8")
        try:
            os.chmod(p, 0o600)
        except OSError:
            pass
        return t


def mcp_token_ok(presented: str | None) -> bool:
    if not presented:
        return False
    return hmac.compare_digest(presented.encode(), mcp_token().encode())


def _now() -> str:
    return time.strftime("%Y-%m-%dT%H:%M:%S%z")


# --- console ------------------------------------------------------------------
def main(argv: list[str] | None = None) -> int:
    import argparse
    import getpass
    ap = argparse.ArgumentParser(prog="python -m docutracex.users",
                                 description="DocuTraceX users from the console of this machine.")
    sub = ap.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("reset-admin", help="set a new admin password (also creates the admin if missing)")
    r.add_argument("--password", help="the new password (asked for when omitted)")
    sub.add_parser("list", help="list the users")
    t = sub.add_parser("mcp-token", help="print the MCP-over-HTTP token")
    t.add_argument("--regenerate", action="store_true", help="make a new one (the old one stops working)")
    a = ap.parse_args(argv)
    if a.cmd == "list":
        for u in list_users():
            print(f"{u['username']:<24} {u['role']:<6} {'active' if u['active'] else 'disabled'}")
        return 0
    if a.cmd == "mcp-token":
        print(regenerate_mcp_token() if a.regenerate else mcp_token())
        return 0
    pw = a.password
    if pw is None:
        pw = getpass.getpass("New admin password: ")
        if pw != getpass.getpass("Repeat it: "):
            print("The two passwords differ.")
            return 1
    try:
        if needs_setup():
            setup_admin(pw)
        else:
            update_user(ADMIN, password=pw, active=True)
    except AuthError as exc:
        print(exc)
        return 1
    print("Admin password set; its sessions were closed.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
